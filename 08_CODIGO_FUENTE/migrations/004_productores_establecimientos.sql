BEGIN;

CREATE TABLE IF NOT EXISTS productores (
    id_productor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    documento VARCHAR(30) UNIQUE,
    telefono VARCHAR(40),
    email VARCHAR(255),
    localidad VARCHAR(120),
    domicilio VARCHAR(200),
    observaciones TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'activo'
);

ALTER TABLE establecimientos
ADD COLUMN IF NOT EXISTS id_productor INTEGER;

INSERT INTO productores (nombre, estado)
SELECT
    'Pendiente de asignación',
    'activo'
WHERE NOT EXISTS (
    SELECT 1
    FROM productores
    WHERE nombre = 'Pendiente de asignación'
);

UPDATE establecimientos
SET id_productor = (
    SELECT id_productor
    FROM productores
    WHERE nombre = 'Pendiente de asignación'
    ORDER BY id_productor
    LIMIT 1
)
WHERE id_productor IS NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_establecimientos_productor'
    ) THEN
        ALTER TABLE establecimientos
        ADD CONSTRAINT fk_establecimientos_productor
        FOREIGN KEY (id_productor)
        REFERENCES productores(id_productor);
    END IF;
END $$;

ALTER TABLE establecimientos
ALTER COLUMN id_productor SET NOT NULL;

CREATE INDEX IF NOT EXISTS
    ix_establecimientos_id_productor
ON establecimientos(id_productor);

COMMIT;